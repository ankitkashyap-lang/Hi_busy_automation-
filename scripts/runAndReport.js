const { exec, spawn } = require('child_process');
const util = require('util');
const execAsync = util.promisify(exec);
const fs = require('fs');
const path = require('path');
const nodemailer = require('nodemailer');
const dotenv = require('dotenv');

dotenv.config();

const QA1_URL = process.env.QA1_BASE_URL || 'https://hiqa1.pooraa.net/';
const QA2_URL = process.env.QA2_BASE_URL || 'https://hiqa2.pooraa.net/';

const QA1_EMAIL = process.env.QA1_REPORT_EMAIL || '';
const QA2_EMAIL = process.env.QA2_REPORT_EMAIL || '';

const SURGE_QA1 = process.env.SURGE_QA1_DOMAIN || 'busy-qa1-automation-report.surge.sh';
const SURGE_QA2 = process.env.SURGE_QA2_DOMAIN || 'busy-qa2-automation-report.surge.sh';

// SMTP config
const SMTP_SERVER = process.env.SMTP_SERVER || process.env.EMAIL_HOST || '';
const SMTP_PORT   = process.env.SMTP_PORT   || process.env.EMAIL_PORT || 587;
const SMTP_USER   = process.env.SMTP_USER   || process.env.EMAIL_USER || '';
const SMTP_PASSWORD = process.env.SMTP_PASSWORD || process.env.EMAIL_PASSWORD || '';

const {
  RESULTS_DIR,
  REPORT_DIR,
  cleanAllureDirs,
  generateAllureReport,
  deployToSurge,
  prepareSurgeDir,
  getReportSummary,
  printBanner
} = require('./allure-utils.js');

const { buildEmailHTML, buildSubject, parsePlaywrightResults, mergeStats } = require('./emailTemplate.js');

const ALLURE_DIR    = path.join(process.cwd(), 'allure');
// Playwright native JSON report (generated by playwright.config.js reporter)
const PW_JSON_REPORT = path.join(process.cwd(), 'reports', 'results.json');

function cleanAllure() {
  console.log('🧹 Cleaning old Allure results...');
  cleanAllureDirs([RESULTS_DIR, REPORT_DIR, ALLURE_DIR]);
  fs.mkdirSync(path.join(ALLURE_DIR, 'qa1', 'results'), { recursive: true });
  fs.mkdirSync(path.join(ALLURE_DIR, 'qa1', 'report'),  { recursive: true });
  fs.mkdirSync(path.join(ALLURE_DIR, 'qa2', 'results'), { recursive: true });
  fs.mkdirSync(path.join(ALLURE_DIR, 'qa2', 'report'),  { recursive: true });
}

function quoteArg(a) {
  if (/[ \t\n\v"|&<>;^]/.test(a)) {
    return `"${a.replace(/"/g, '\\"')}"`;
  }
  return a;
}

function runTestsAsync(envName, baseUrl, resultsDir, forwardArgs) {
  return new Promise((resolve) => {
    console.log(`\n🚀 Executing tests on ${envName} (${baseUrl})`);

    const env = {
      ...process.env,
      ENVIRONMENT: envName.toLowerCase(),
      BASE_URL: baseUrl,
      ALLURE_RESULTS_DIR: resultsDir,
      CI: '1' // Force CI mode to prevent HTML reporter from hanging on failure
    };

    const commandString = `npx playwright test ${forwardArgs.map(quoteArg).join(' ')}`;
    const child = spawn(commandString, { stdio: 'inherit', env, shell: true });

    child.on('close', (code) => { resolve(code === 0); });
  });
}

async function generateReportAsync(resultsDir, reportDir) {
  console.log(`\n📊 Generating Allure report into ${reportDir}`);
  try {
    await generateAllureReport(resultsDir, reportDir);
    console.log(`✅ Allure report generated for ${reportDir}`);
  } catch (e) {
    console.error(`❌ Failed to generate Allure report for ${reportDir}:`, e.message);
  }
}

async function deployToSurgeAsync(reportDir, domain) {
  console.log(`\n☁️  Deploying report to Surge: https://${domain}`);
  try {
    const url = await deployToSurge(reportDir, domain);
    console.log(`✅ Deployed to Surge: ${url}`);
    return url;
  } catch (e) {
    console.error(`❌ Failed to deploy to Surge for ${domain}:`, e.message);
    return null;
  }
}

/**
 * Send a rich HTML email with full test execution summary.
 */
async function sendEmail(envName, recipient, reportUrl, passed, allureSummary, baseUrl, pwHtmlReportUrl) {
  if (!SMTP_SERVER || !SMTP_USER) {
    console.log(`\n⚠️  SMTP not configured – skipping email for ${envName}.`);
    return;
  }

  // Parse Playwright JSON report for suite breakdown & failed test list
  const pwStats = parsePlaywrightResults(PW_JSON_REPORT);

  // Merge Allure totals (preferred) with Playwright JSON stats
  const stats = mergeStats(allureSummary, pwStats);

  // Check Playwright default HTML report
  const pwHtmlPath = path.join(process.cwd(), 'reports', 'html', 'index.html');
  const hasPwHtml  = fs.existsSync(pwHtmlPath);

  // Separate Playwright HTML surge URL (if deployed or env set)
  const pwHtmlUrl = pwHtmlReportUrl
    || (process.env[`SURGE_PW_HTML_${envName.toUpperCase()}_DOMAIN`]
        ? `https://${process.env[`SURGE_PW_HTML_${envName.toUpperCase()}_DOMAIN`]}`
        : (process.env.SURGE_PW_HTML_DOMAIN ? `https://${process.env.SURGE_PW_HTML_DOMAIN}` : null));

  const htmlBody = buildEmailHTML({
    envName,
    baseUrl:             baseUrl || '',
    reportUrl:           reportUrl || '#',
    playwrightReportUrl: pwHtmlUrl,
    hasAttachment:       hasPwHtml,
    passed,
    total:   stats.total,
    pass:    stats.pass,
    fail:    stats.fail,
    broken:  stats.broken   || 0,
    skipped: stats.skipped  || 0,
    duration:    pwStats.duration,
    timestamp:   new Date().toISOString(),
    suites:      pwStats.suites,
    failedTests: pwStats.failedTests,
  });

  const subject = buildSubject(envName, passed, stats.total, stats.pass, stats.fail);

  console.log(`\n📧 Sending email to: ${recipient}`);
  console.log(`   Subject: ${subject}`);

  const attachments = [];
  if (hasPwHtml) {
    attachments.push({
      filename: `Playwright-Report-${envName}.html`,
      path: pwHtmlPath,
    });
    console.log(`   📎 Attaching Playwright HTML report: ${pwHtmlPath}`);
  }

  const transporter = nodemailer.createTransport({
    host: SMTP_SERVER,
    port: SMTP_PORT,
    secure: SMTP_PORT == 465,
    auth: { user: SMTP_USER, pass: SMTP_PASSWORD },
  });

  try {
    const info = await transporter.sendMail({
      from:    `"Hi Busy Automation" <${SMTP_USER}>`,
      to:      recipient,
      subject,
      html:    htmlBody,
      attachments,
    });
    console.log(`✅ Email sent: ${info.messageId}`);
  } catch (error) {
    console.error('❌ Error sending email:', error);
  }
}

async function processEnvironment(envName, url, email, surgeDomain, resultsDir, reportDir, forwardArgs) {
  const passed = await runTestsAsync(envName, url, resultsDir, forwardArgs);
  await generateReportAsync(resultsDir, reportDir);
  const reportUrl = await deployToSurgeAsync(reportDir, surgeDomain);
  const summary   = getReportSummary(reportDir);

  // Deploy Playwright native HTML report to Surge if domain configured
  const pwHtmlDir = path.join(process.cwd(), 'reports', 'html');
  const pwDomain  = process.env[`SURGE_PW_HTML_${envName.toUpperCase()}_DOMAIN`] || process.env.SURGE_PW_HTML_DOMAIN;
  let pwReportUrl = null;
  if (pwDomain && fs.existsSync(path.join(pwHtmlDir, 'index.html'))) {
    console.log(`\n☁️  Deploying Playwright HTML report to Surge: https://${pwDomain}`);
    pwReportUrl = await deployToSurgeAsync(pwHtmlDir, pwDomain);
  }

  if (reportUrl) {
    printBanner({ testStatus: passed ? 'PASSED' : 'FAILED', envName, url: reportUrl, summary });
  }

  await sendEmail(envName, email, reportUrl || `https://${surgeDomain}`, passed, summary, url, pwReportUrl);
  return passed;
}

async function main() {
  const args = process.argv.slice(2);
  let targetEnv = 'both';

  // Extract custom --env flag if provided
  const envIndex = args.findIndex(arg => arg.startsWith('--env='));
  if (envIndex !== -1) {
    targetEnv = args[envIndex].split('=')[1].toLowerCase();
    args.splice(envIndex, 1);
  }

  cleanAllure();
  console.log(`\n⚡ Starting execution for: ${targetEnv.toUpperCase()}...`);

  const tasks = [];

  if (targetEnv === 'qa1' || targetEnv === 'both') {
    tasks.push(processEnvironment(
      'QA1', QA1_URL, QA1_EMAIL, SURGE_QA1,
      path.join(ALLURE_DIR, 'qa1', 'results'),
      path.join(ALLURE_DIR, 'qa1', 'report'),
      args
    ));
  }

  if (targetEnv === 'qa2' || targetEnv === 'both') {
    tasks.push(processEnvironment(
      'QA2', QA2_URL, QA2_EMAIL, SURGE_QA2,
      path.join(ALLURE_DIR, 'qa2', 'results'),
      path.join(ALLURE_DIR, 'qa2', 'report'),
      args
    ));
  }

  if (tasks.length > 0) {
    const results  = await Promise.all(tasks);
    const allPassed = results.every(res => res === true);
    console.log(`\n🎉 Execution completed for ${targetEnv.toUpperCase()}.`);
    if (!allPassed) process.exit(1);
  } else {
    console.log(`\n⚠️  Invalid environment. Use --env=qa1, --env=qa2, or --env=both.`);
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
